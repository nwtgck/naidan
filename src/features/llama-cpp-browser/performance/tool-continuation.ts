import { z } from 'zod';
import type { GenerateInput, GenerationResult } from '@/features/llama-cpp-browser/types';

const toolName = 'record_sample';
const sample = [
  'The archive contains a folded map, a blue notebook, a glass compass, and four labeled envelopes. The station clock shows seven minutes past the hour. The north window looks over a garden of rosemary and lavender. A bicycle waits beside the side entrance, where the stone steps are wet. The caretaker lists the room numbers on a sheet of paper and leaves it under a brass weight.',
  'At the front desk, a visitor returns an umbrella and asks when the reading room will open. Across the hall a librarian pushes a cart past the lamps and closes a cabinet marked with a small bird. Two postcards lie between the pages of a book about river bridges. The notice on the stairwell says the west door will be closed until noon. Visitors can reach the courtyard by following the green tiles.',
].join(' ');
export const toolCallPrompt = `\
Call ${toolName} once. Set label to archive and copy the entire English passage below into passage. After receiving the result, explain in one sentence what the tool reported.

${sample}`;
export const toolResult = '{"ok":true}';
export const toolCallTokenLimit = 512;
export const toolContinuationTokenLimit = 32;

export const performanceTools: NonNullable<GenerateInput['tools']> = [{
  type: 'function',
  function: {
    name: toolName,
    description: 'Record an English passage with a short label. Returns a small success result.',
    parameters: {
      type: 'object',
      properties: {
        label: { type: 'string' },
        passage: { type: 'string' },
      },
      required: ['label', 'passage'],
      additionalProperties: false,
    },
  },
}];

const sampleArgumentsSchema = z.object({
  label: z.literal('archive'),
  passage: z.string().trim().min(256).max(1024),
}).strict();

export function toolCallForContinuation({ output }: { output: GenerationResult }): GenerationResult['toolCalls'][number] | undefined {
  const [call] = output.toolCalls;
  if (output.finishReason !== 'stop' || output.toolCalls.length !== 1 || !call || call.function.name !== toolName || call.function.arguments.length > 4096) {
    return undefined;
  }
  // Validate the fixture without rewriting the bytes generated by the model.
  try {
    if (!sampleArgumentsSchema.safeParse(JSON.parse(call.function.arguments)).success) {
      return undefined;
    }
    // Like ordinary chat, provide a nine-character alphanumeric ID when the
    // template does not generate one. This fixture has one call and no history.
    return call.id ? call : { ...call, id: 'perfcall1' };
  } catch {
    return undefined;
  }
}

